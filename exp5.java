public class exp5 {
    public static void main(String[] args) {
        byte b = 8;//the byte data type is of 1 bytr size
        System.out.println(b);
        char ch = 'a';////the charactar data type is of 2 bytr size
        System.out.println(ch);
        boolean var = false;//the boolean data type is of 1 bytr size
        System.out.println(var);
        int x = 76;//the integer data type is of 4 bytr size
        System.out.println(x);
        short g = 67;//the short data type is of 2 bytr size
        System.out.println(g);
        long n = 90;//the long data type is of 8 bytr size
        System.out.println(n);
        float r = 54.43f;//the float data type is of 4 bytr size, and we also have to write 'f' at the end or it will give an error
        System.out.println(r);
        double y = 97.33745387458;//the double data type is of 8 byte
        System.out.println(y);


    }
    
}
