import java.util.*;
public class exp70{
    public static void main(String[] args) {
        //swap value means exchange  the value of one integer
        int a = 45;
        int b = 56;

        //swap
        int temp = a;
        a=b;
        b = temp;
        System.out.println(" 'a' is : " + a);
        System.out.println(" 'b' is : " + b);
    }
}
