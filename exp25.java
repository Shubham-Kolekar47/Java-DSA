import java.util.*;
public class exp25 {
    public static void main(String[] args) {
        int a = 10; // relational operators
        int b = 5;
        System.out.println((a == b));// it will show false as the answer 
        System.out.println((a!=b));// it will return a as true as they are not equal
        System.out.println((a>b));
        System.out.println((a<b));
        System.out.println((a>=b));
        System.out.println((a<=b));
    }
}
