import java.util.*;
public class exp24 {
    public static void main(String[] args) {
        int a = 10; // decrement operators
        int b = --a;
        System.out.println(a);
        System.out.println(b);
        int c = 10;
        int d = c--;
        System.out.println(c);
        System.out.println(d);
    }
}
